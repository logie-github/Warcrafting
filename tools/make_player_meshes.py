#!/usr/bin/env python3
"""Convert the four original Warcraft III player candidates into game display lists.

usage: make_player_meshes.py <wc3 root> <out .c> <out texture dir>

Output C (pc_player_meshes.c): per model k: pc_player<k>_v / _tex / _dl, and the tables
pc_player_dls[], pc_player_scale[] (game-unit scale for equal height). The skins ship as
tex1_32x32_<hash>_0.dds (RGBA/BC3) replacing each model's placeholder I4 texture.
"""
import os, sys, glob
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np, xxhash
from PIL import Image
import render_player_candidates as RP
from make_peon_mesh import chunks

MODELS = [('Peasant', 'peasant.blp', 'ReignOfChaos'), ('Peon', 'peon.blp', 'ReignOfChaos'),
          ('Sorceress', 'sorceress.blp', 'ReignOfChaos'), ('Dark Ranger', 'bansheeranger.blp', 'FrozenThrone')]
TARGET_HEIGHT = 7900.0   # game model units (actor scale 0.01 -> ~79 world units)


def find_tex(root, name, prefer):
    hits = [p for p in sorted(glob.glob(root + '**/*', recursive=True)) if os.path.basename(p).lower() == name]
    if not hits:
        raise SystemExit('texture not found: ' + name)
    pref = [p for p in hits if os.sep + prefer + os.sep in p or '/' + prefer + '/' in p]
    print('  texture', (pref or hits)[0].replace(root, ''), 'of', len(hits), 'candidates')
    return Image.open((pref or hits)[0]).convert('RGBA')


def mesh(root, label):
    spec = [s for s in RP.SPEC if s[0] == label][0]
    m = RP.build(spec[1], spec[2], spec[3])
    V = []; UV = []; T = []; off = 0
    for g in m['geosets']:
        V.append(g['v']); UV.append(g['uv']); T.append(g['idx'] + off); off += len(g['v'])
    V = np.concatenate(V); UV = np.concatenate(UV); T = np.concatenate(T)
    P = np.stack([-V[:, 1], V[:, 2], V[:, 0]], 1)      # model Z up, faces +X -> game Y up, faces +Z
    P[:, 1] -= P[:, 1].min()
    return P, UV, T


def main(root, out_c, out_dir):
    root = root.rstrip('/') + '/'
    RP.R = root
    os.makedirs(out_dir, exist_ok=True)
    lines = ['/* generated by tools/make_player_meshes.py - original Warcraft III models, bind pose */',
             '#include "libforest/gbi_extensions.h"', '#include "PR/gbi.h"', '#include "types.h"', '']
    scales = []
    for k, (label, texname, prefer) in enumerate(MODELS):
        P, UV, T = mesh(root, label)
        height = float(P[:, 1].max())
        scales.append(TARGET_HEIGHT / height / 100.0)       # applied after the 0.01 actor scale
        placeholder = bytes(((i * (31 + 6 * k) + 11 + 17 * k) & 0xFF) for i in range(0x200))
        h = xxhash.xxh64(placeholder, seed=0).hexdigest()
        find_tex(root, texname, prefer).save(os.path.join(out_dir, f'tex1_32x32_{h}_0.dds'), pixel_format='DXT5')
        lines.append(f'u8 pc_player{k}_tex[0x200] ATTRIBUTE_ALIGN(32) = {{' + ','.join(str(b) for b in placeholder) + '};')
        vtx = []; dl = []
        for grp in chunks([tuple(int(i) for i in t) for t in T]):
            order = {}
            for t in grp:
                for v in t: order.setdefault(v, len(order))
            base = len(vtx)
            for v in order:
                x, y, z = P[v] * 100.0 / 100.0
                u, w = UV[v]
                vtx.append(f'{{{{{{ {int(round(x))}, {int(round(y))}, {int(round(z))} }}, 1, {{ {int(round(u * 1024))}, {int(round(w * 1024))} }}, {{ 255, 255, 255, 255 }} }}}}')
            dl.append(f'    gsSPVertex(&pc_player{k}_v[{base}], {len(order)}, 0),')
            idx = [order[v] for t in grp for v in t]
            n = len(grp)
            if len(idx) < 9: idx += [0] * (9 - len(idx))
            dl.append(f'    gsSPNTrianglesInit_5b({n}, ' + ', '.join(map(str, idx[:9])) + '),')
            rest = idx[9:]
            while rest:
                c = rest[:12] + [0] * (12 - len(rest[:12]))
                dl.append('    gsSPNTriangles_5b(' + ', '.join(map(str, c)) + '),')
                rest = rest[12:]
        lines.append(f'Vtx pc_player{k}_v[{len(vtx)}] = {{')
        lines += ['    ' + v + ',' for v in vtx]
        lines += ['};', f'Gfx pc_player{k}_dl[] = {{',
                  '    gsSPTexture(0, 0, 0, G_TX_RENDERTILE, G_ON),',
                  '    gsSPLoadGeometryMode(G_ZBUFFER | G_SHADE | G_SHADING_SMOOTH),',
                  '    gsDPSetRenderMode(G_RM_FOG_SHADE_A, G_RM_AA_ZB_OPA_SURF2),',
                  '    gsDPSetCombineLERP(TEXEL0, 0, SHADE, 0, 0, 0, 0, TEXEL0, PRIMITIVE, 0, COMBINED, 0, 0, 0, 0, COMBINED),',
                  '    gsDPSetPrimColor(0, 128, 255, 255, 255, 255),',
                  f'    gsDPSetTextureImage_Dolphin(G_IM_FMT_I, G_IM_SIZ_4b, 32, 32, pc_player{k}_tex),',
                  '    gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE, 0, 15, GX_REPEAT, GX_REPEAT, 0, 0),',
                  '    gsDPSetTileSize(G_TX_RENDERTILE, 0, 0, 124, 124),'] + dl + ['    gsSPEndDisplayList(),', '};', '']
        print(label, 'verts', len(vtx), 'tris', len(T), 'height', round(height, 1), 'scale', round(scales[-1] * 100, 1), 'hash', h)
    n = len(MODELS)
    lines.append(f'Gfx* pc_player_dls[{n}] = {{ ' + ', '.join(f'pc_player{k}_dl' for k in range(n)) + ' };')
    lines.append(f'float pc_player_scale[{n}] = {{ ' + ', '.join(f'{s * 100.0:.2f}f' for s in scales) + ' };')
    lines.append(f'const char* pc_player_names[{n}] = {{ ' + ', '.join(f'"{m[0]}"' for m in MODELS) + ' };')
    open(out_c, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main(*sys.argv[1:4])
