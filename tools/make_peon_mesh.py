#!/usr/bin/env python3
"""Convert an original Warcraft III MDX model (bind pose, selected geosets) into a game display list.

usage: make_peon_mesh.py <wc3 root> <out .c> <out texture dds dir> [name]

Writes pc_peon_mesh.c (Vtx array + Gfx display list + placeholder I4 texture) and the replacement
texture as tex1_32x32_<hash>_0.dds (RGBA). The texture pack swaps the placeholder for the real skin.
"""
import os, sys, glob
sys.path.insert(0, os.path.dirname(__file__))
import numpy as np
import xxhash
from PIL import Image
import mdx_render as M
import render_player_candidates as RP


def chunks(tris, nverts_max=32, ntri_max=100):
    out = []; cur = []; used = {}
    for t in tris:
        new = [v for v in t if v not in used]
        if len(used) + len(set(new)) > nverts_max or len(cur) >= ntri_max:
            out.append(cur); cur = []; used = {}
        cur.append(t)
        for v in t:
            used.setdefault(v, len(used))
    if cur: out.append(cur)
    return out


def main(root, out_c, out_dir, scale=1.0):
    RP.R = root.rstrip('/') + '/'
    spec = [s for s in RP.SPEC if s[0] == 'Peon'][0]
    m = RP.build(spec[1], spec[2], spec[3])
    # merge geosets
    V = []; UV = []; T = []; off = 0
    for g in m['geosets']:
        V.append(g['v']); UV.append(g['uv']); T.append(g['idx'] + off); off += len(g['v'])
    V = np.concatenate(V); UV = np.concatenate(UV); T = np.concatenate(T)
    # model Z up, faces +X  ->  game Y up, faces +Z: (x,y,z) -> (-y, z, x)
    P = np.stack([-V[:, 1], V[:, 2], V[:, 0]], 1)
    P[:, 1] -= P[:, 1].min()
    # source texture
    tex = None
    for p in glob.glob(RP.R + '**/*', recursive=True):
        if os.path.basename(p).lower() == 'peon.blp':
            tex = Image.open(p).convert('RGBA'); break
    placeholder = bytes((i * 37 + 11) & 0xFF for i in range(0x200))
    h = xxhash.xxh64(placeholder, seed=0).hexdigest()
    os.makedirs(out_dir, exist_ok=True)
    tex.save(os.path.join(out_dir, f'tex1_32x32_{h}_0.dds'), pixel_format='DXT5')
    lines = ['/* generated by tools/make_peon_mesh.py - original Warcraft III Peon, bind pose */',
             '#include "libforest/gbi_extensions.h"', '#include "PR/gbi.h"', '#include "types.h"', '',
             'u8 pc_peon_tex[0x200] ATTRIBUTE_ALIGN(32) = {' + ','.join(str(b) for b in placeholder) + '};', '']
    groups = chunks([tuple(int(i) for i in t) for t in T])
    vtx = []; dl = []
    for grp in groups:
        order = {}
        for t in grp:
            for v in t: order.setdefault(v, len(order))
        base = len(vtx)
        for v in order:
            x, y, z = (P[v] * scale)
            u, w = UV[v]
            vtx.append(f'{{{{{{ {int(round(x))}, {int(round(y))}, {int(round(z))} }}, 1, {{ {int(round(u * 1024))}, {int(round(w * 1024))} }}, {{ 255, 255, 255, 255 }} }}}}')
        dl.append(f'    gsSPVertex(&pc_peon_v[{base}], {len(order)}, 0),')
        idx = [order[v] for t in grp for v in t]
        n = len(grp)
        idx += [0] * (3 * 3 - len(idx)) if len(idx) < 9 else []
        dl.append(f'    gsSPNTrianglesInit_5b({n}, ' + ', '.join(map(str, idx[:9])) + '),')
        rest = idx[9:]
        while rest:
            c = rest[:12] + [0] * (12 - len(rest[:12]))
            dl.append('    gsSPNTriangles_5b(' + ', '.join(map(str, c)) + '),')
            rest = rest[12:]
    lines.append(f'Vtx pc_peon_v[{len(vtx)}] = {{')
    lines += ['    ' + v + ',' for v in vtx]
    lines += ['};', '', 'Gfx pc_peon_dl[] = {',
              '    gsSPTexture(0, 0, 0, G_TX_RENDERTILE, G_ON),',
              '    gsSPLoadGeometryMode(G_ZBUFFER | G_SHADE | G_SHADING_SMOOTH),',
              '    gsDPSetRenderMode(G_RM_FOG_SHADE_A, G_RM_AA_ZB_OPA_SURF2),',
              '    gsDPSetCombineLERP(TEXEL0, 0, SHADE, 0, 0, 0, 0, TEXEL0, PRIMITIVE, 0, COMBINED, 0, 0, 0, 0, COMBINED),',
              '    gsDPSetPrimColor(0, 128, 255, 255, 255, 255),',
              '    gsDPSetTextureImage_Dolphin(G_IM_FMT_I, G_IM_SIZ_4b, 32, 32, pc_peon_tex),',
              '    gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE, 0, 15, GX_REPEAT, GX_REPEAT, 0, 0),',
              '    gsDPSetTileSize(G_TX_RENDERTILE, 0, 0, 124, 124),']
    lines += dl + ['    gsSPEndDisplayList(),', '};', '']
    open(out_c, 'w').write('\n'.join(lines))
    print('verts', len(vtx), 'tris', len(T), 'groups', len(groups), 'tex hash', h, 'height', P[:, 1].max())


if __name__ == '__main__':
    main(*sys.argv[1:4])
