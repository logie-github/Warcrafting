#!/usr/bin/env python3
"""Bake the Warcraft III building library used by the in-game build mode.

usage: make_lib_meshes.py <wb_models.json> <out .c> <texture dir> [lib list json out]

Each model is centred on its footprint with its base at y = 0, stored as s16 in native Warcraft units
(the game scales by a runtime factor). One placeholder I4 texture exists per distinct skin; the skins
ship as tex1_32x32_<hash>_0.dds.
"""
import sys, os, json, base64, io
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np, xxhash
from PIL import Image
from make_peon_mesh import chunks

LIGHT = np.array([.4, .8, .5]); LIGHT /= np.linalg.norm(LIGHT)

def pick(W):
    out = []
    for cat, names in sorted(W['folders'].items()):
        ok = any(k in cat for k in ('Human buildings', 'LordaeronSummer', 'Village', 'Orc buildings', 'Barrens')) or 'Cityscape' in cat
        for n in sorted(names):
            if ok and not ('Cityscape' in cat and 'Ruin' in n):
                out.append((cat, n))
    return out

def main(wb, out_c, out_dir, list_out=None):
    W = json.load(open(wb)); os.makedirs(out_dir, exist_ok=True)
    sel = pick(W)
    L = ['/* generated by tools/make_lib_meshes.py - Warcraft III building library for the in-game build mode */',
         '#include "libforest/gbi_extensions.h"', '#include "PR/gbi.h"', '#include "types.h"', '']
    texmap = {}; hashes = set()
    def placeholder_for(ti):
        if ti in texmap: return texmap[ti]
        n = len(texmap)
        ph = b''.join(xxhash.xxh64(('lib%d_%d' % (n, j)).encode(), seed=11).digest() for j in range(64))
        h = xxhash.xxh64(ph, seed=0).hexdigest(); assert h not in hashes; hashes.add(h)
        du = W['textures'][ti]
        Image.open(io.BytesIO(base64.b64decode(du.split(',', 1)[1]))).convert('RGBA').save(os.path.join(out_dir, f'tex1_32x32_{h}_0.dds'), pixel_format='DXT5')
        L.append(f'u8 pc_lib_tex{n}[0x200] ATTRIBUTE_ALIGN(32) = {{' + ','.join(str(x) for x in ph) + '};')
        texmap[ti] = n; return n
    info = []
    for mi, (cat, name) in enumerate(sel):
        m = W['models'][name]; lo = np.array(m['min']); hi = np.array(m['max'])
        gl = [f'Gfx pc_lib_{mi}_dl[] = {{',
              '    gsSPTexture(0, 0, 0, G_TX_RENDERTILE, G_ON),',
              '    gsSPLoadGeometryMode(G_ZBUFFER | G_SHADE | G_SHADING_SMOOTH),',
              '    gsDPSetRenderMode(G_RM_FOG_SHADE_A, G_RM_AA_ZB_OPA_SURF2),',
              '    gsDPSetCombineLERP(TEXEL0, 0, SHADE, 0, 0, 0, 0, TEXEL0, PRIMITIVE, 0, COMBINED, 0, 0, 0, 0, COMBINED),',
              '    gsDPSetPrimColor(0, 128, 255, 255, 255, 255),']
        c0 = np.array([(lo[0] + hi[0]) / 2, lo[1], (lo[2] + hi[2]) / 2])
        for k, me in enumerate(m['meshes']):
            q = np.frombuffer(base64.b64decode(me['pos']), np.uint16).reshape(-1, 3).astype(np.float64)
            P = lo + q / 65535 * (hi - lo)
            UV = np.frombuffer(base64.b64decode(me['uv']), np.int16).reshape(-1, 2) / 2048.0
            T = np.frombuffer(base64.b64decode(me['idx']), np.uint16).reshape(-1, 3).astype(np.int64)
            N = np.zeros_like(P)
            fn = np.cross(P[T[:, 1]] - P[T[:, 0]], P[T[:, 2]] - P[T[:, 0]])
            for j in range(3): np.add.at(N, T[:, j], fn)
            N /= np.maximum(np.linalg.norm(N, axis=1, keepdims=True), 1e-9)
            col = np.round(np.clip(np.maximum(N @ LIGHT, 0) * .55 + .55, 0, 1) * 255).astype(int)
            Q = P - c0
            ph = placeholder_for(me['tex'])
            gl += [f'    gsDPSetTextureImage_Dolphin(G_IM_FMT_I, G_IM_SIZ_4b, 32, 32, pc_lib_tex{ph}),',
                   '    gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE, 0, 15, GX_REPEAT, GX_REPEAT, 0, 0),',
                   '    gsDPSetTileSize(G_TX_RENDERTILE, 0, 0, 124, 124),']
            groups = chunks([tuple(int(v) for v in t) for t in T])
            vl = []; base = 0
            for grp in groups:
                order = {}
                for t in grp:
                    for v in t: order.setdefault(v, len(order))
                for v in order:
                    x, y, z = np.round(Q[v]).astype(int)
                    u, w = np.clip(np.round(UV[v] * 1024), -32768, 32767).astype(int)
                    vl.append(f'{{{{{{ {x}, {y}, {z} }}, 1, {{ {u}, {w} }}, {{ {col[v]}, {col[v]}, {col[v]}, 255 }} }}}}')
                gl.append(f'    gsSPVertex(&pc_lib_{mi}_{k}_v[{base}], {len(order)}, 0),')
                idx = [order[v] for t in grp for v in t]; cnt = len(grp)
                if len(idx) < 9: idx += [0] * (9 - len(idx))
                gl.append(f'    gsSPNTrianglesInit_5b({cnt}, ' + ', '.join(map(str, idx[:9])) + '),')
                rest = idx[9:]
                while rest:
                    cc = rest[:12] + [0] * (12 - len(rest[:12]))
                    gl.append('    gsSPNTriangles_5b(' + ', '.join(map(str, cc)) + '),')
                    rest = rest[12:]
                base += len(order)
            L.append(f'Vtx pc_lib_{mi}_{k}_v[{len(vl)}] = {{'); L += ['    ' + v + ',' for v in vl]; L.append('};')
        gl += ['    gsSPEndDisplayList(),', '};']; L += gl
        w = hi[0] - lo[0]; d = hi[2] - lo[2]; h = hi[1] - lo[1]
        info.append(dict(name=name, cat=cat, path=m['path'], w=float(w), d=float(d), h=float(h)))
    n = len(sel)
    L.append(f'int pc_lib_count = {n};')
    L.append(f'Gfx* pc_lib_dls[{n}] = {{ ' + ', '.join(f'pc_lib_{i}_dl' for i in range(n)) + ' };')
    L.append(f'const char* pc_lib_names[{n}] = {{ ' + ', '.join('"%s"' % x['name'].replace('"', '') for x in info) + ' };')
    L.append(f'float pc_lib_size[{n}][3] = {{ ' + ', '.join('{ %.1ff, %.1ff, %.1ff }' % (x['w'], x['d'], x['h']) for x in info) + ' };')
    open(out_c, 'w').write('\n'.join(L) + '\n')
    if list_out: json.dump(info, open(list_out, 'w'), indent=1)
    print(n, 'models', len(texmap), 'skins')

if __name__ == '__main__':
    main(*sys.argv[1:5])
