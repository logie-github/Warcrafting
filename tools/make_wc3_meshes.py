#!/usr/bin/env python3
"""Bake original Warcraft III models (+ Stand / Walk / action animations) into game data.

usage: make_wc3_meshes.py <wc3 root> <out .c> <out texture dir>

Models: 0 Peasant, 1 Peon, 2 Sorceress, 3 Dark Ranger (player options), 4 Thrall, 5 Grom Hellscream.
Output pc_wc3_meshes.c: per model a static triangle display list plus a Vtx array whose positions the
game overwrites each frame from the baked pose tables (Stand 6 frames, Walk 8, Action 8).
Skins ship as tex1_32x32_<hash>_0.dds replacing each model's placeholder I4 texture.
"""
import os, sys, glob
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np, xxhash
from PIL import Image
import mdx_anim as A
import mdx_render as M
import render_player_candidates as RP
from make_peon_mesh import chunks

TARGET_HEIGHT = 7900.0 * 2.0 / 3.0       # game model units; 2/3 of the first version
FRAMES = {'stand': 6, 'walk': 8, 'act': 8}
SEQ = {'stand': ['Stand'], 'walk': ['Walk'],
       'act': ['Attack', 'Attack - 1', 'Spell Attack', 'Spell']}
# label, mdx path, dropped geosets (None = auto: effect-only materials), dropped components, texture root preference
MODELS = [
    ('Peasant', 'ReignOfChaos/Units/Human/Peasant/peasant.mdx', {2, 3, 4, 5}, {0: {4, 7}}, 'ReignOfChaos'),
    ('Peon', 'ReignOfChaos/Units/Orc/Peon/peon.mdx', {2, 3, 4}, {0: {0, 5}}, 'ReignOfChaos'),
    ('Sorceress', 'ReignOfChaos/Units/Human/Sorceress/Sorceress.mdx', {2}, {}, 'ReignOfChaos'),
    ('Dark Ranger', 'FrozenThrone/Units/Creeps/BansheeRanger/BansheeRanger.mdx', {2, 3, 4, 5, 6}, {0: {5, 6, 8, 10, 11}}, 'FrozenThrone'),
    ('Thrall', 'ReignOfChaos/Units/Orc/Thrall/Thrall.mdx', None, {}, 'ReignOfChaos'),
    ('Grom Hellscream', 'ReignOfChaos/Units/Orc/Hellscream/Hellscream.mdx', {3, 4, 5, 6}, {}, 'ReignOfChaos'),
]


def find_tex(root, path, prefer):
    name = path.replace('\\', '/').split('/')[-1].lower()
    hits = [p for p in sorted(glob.glob(root + '**/*', recursive=True)) if os.path.basename(p).lower() == name]
    if not hits:
        raise SystemExit('texture not found: ' + path)
    pref = [p for p in hits if '/' + prefer + '/' in p]
    return Image.open((pref or hits)[0]).convert('RGBA')


def comps(g):
    return RP.comps(g)


def build(root, label, path, dropg, dropc):
    mm = M.parse_mdx(open(root + path, 'rb').read())
    anim = A.Model(open(root + path, 'rb').read())
    if dropg is None:
        dropg = {gi for gi, g in enumerate(mm['geosets'])
                 if all(l['filter'] in (3, 4) for l in mm['materials'][g['mat']])}
    keep = [gi for gi in range(len(mm['geosets'])) if gi not in dropg]
    tris = {}
    for gi in keep:
        g = mm['geosets'][gi]
        idx = g['idx']
        if gi in dropc:
            lab = comps(g)
            idx = idx[np.array([l not in dropc[gi] for l in lab])]
        tris[gi] = idx
    # texture of the kept geosets: first replaceable-0 texture of the last non-effect layer
    tex_path = None
    for gi in keep:
        for l in reversed(mm['materials'][mm['geosets'][gi]['mat']]):
            t = mm['textures'][l['tex']]
            if t[0] == 0 and t[1] and l['filter'] not in (3, 4):
                tex_path = t[1]; break
        if tex_path: break
    # pruned vertex list over all kept geosets
    base = 0; offs = {}; allt = []
    for gi in keep:
        offs[gi] = base; allt.append(tris[gi] + base); base += len(mm['geosets'][gi]['v'])
    T = np.concatenate(allt)
    used = np.unique(T)
    remap = -np.ones(base, int); remap[used] = np.arange(len(used))
    T = remap[T]
    UV = np.concatenate([mm['geosets'][gi]['uv'] for gi in keep])[used]
    def pack(per_geo):
        V = np.concatenate([per_geo[gi] for gi in keep])[used]
        return np.stack([-V[:, 1], V[:, 2], V[:, 0]], 1)    # model Z up, faces +X -> game Y up, faces +Z
    rest = pack({gi: mm['geosets'][gi]['v'].astype(np.float64) for gi in keep})
    lift = rest[:, 1].min()
    seqs = {}
    for key, names in SEQ.items():
        frames = None
        for nm in names:
            if anim.seq(nm):
                frames = anim.bake(nm, FRAMES[key]); break
        if frames is None:
            frames = anim.bake('Stand', FRAMES[key])
        seqs[key] = [pack({gi: f[gi] for gi in keep}) - np.array([0, lift, 0]) for f in frames]
    P0 = rest - np.array([0, lift, 0])
    height = float(seqs['stand'][0][:, 1].max())      # standing height, not the arms-up peak of the action pose
    return dict(label=label, T=T, UV=UV, P0=P0, seqs=seqs, height=height, tex_path=tex_path)


def main(root, out_c, out_dir):
    root = root.rstrip('/') + '/'
    RP.R = root
    os.makedirs(out_dir, exist_ok=True)
    L = ['/* generated by tools/make_wc3_meshes.py - original Warcraft III models with baked Stand/Walk/Action poses */',
         '#include "libforest/gbi_extensions.h"', '#include "PR/gbi.h"', '#include "types.h"', '']
    n = len(MODELS)
    scales = []
    for k, (label, path, dropg, dropc, prefer) in enumerate(MODELS):
        d = build(root, label, path, dropg, dropc)
        scales.append(TARGET_HEIGHT / d['height'])
        placeholder = bytes(((i * (31 + 6 * k) + 11 + 17 * k) & 0xFF) for i in range(0x200))
        h = xxhash.xxh64(placeholder, seed=0).hexdigest()
        find_tex(root, d['tex_path'], prefer).save(os.path.join(out_dir, f'tex1_32x32_{h}_0.dds'), pixel_format='DXT5')
        nv = len(d['P0'])
        L.append(f'u8 pc_wc3_{k}_tex[0x200] ATTRIBUTE_ALIGN(32) = {{' + ','.join(str(b) for b in placeholder) + '};')
        vt = []
        for i in range(nv):
            x, y, z = d['P0'][i]; u, w = d['UV'][i]
            vt.append(f'{{{{{{ {int(round(x))}, {int(round(y))}, {int(round(z))} }}, 1, {{ {int(round(u * 1024))}, {int(round(w * 1024))} }}, {{ 255, 255, 255, 255 }} }}}}')
        # triangle chunks: vertex groups of <=32 loaded at base offsets into the (pruned) vertex array
        order_groups = chunks([tuple(int(i) for i in t) for t in d['T']])
        dl = []
        # to keep each group's vertices contiguous, re-emit a group-local vertex array after the main one
        gv = []
        for grp in order_groups:
            order = {}
            for t in grp:
                for v in t: order.setdefault(v, len(order))
            dl.append((order, grp))
        # group vertex arrays are views by index list: store as an index table used at frame update
        gidx = []
        for order, grp in dl:
            gidx.append(list(order.keys()))
        flat = [v for g in gidx for v in g]
        L.append(f'Vtx pc_wc3_{k}_v[{len(flat)}] = {{')
        for v in flat:
            L.append('    ' + vt[v] + ',')
        L += ['};', f'const u16 pc_wc3_{k}_map[{len(flat)}] = {{' + ','.join(str(v) for v in flat) + '};']
        gl = [f'Gfx pc_wc3_{k}_dl[] = {{',
              '    gsSPTexture(0, 0, 0, G_TX_RENDERTILE, G_ON),',
              '    gsSPLoadGeometryMode(G_ZBUFFER | G_SHADE | G_SHADING_SMOOTH),',
              '    gsDPSetRenderMode(G_RM_FOG_SHADE_A, G_RM_AA_ZB_OPA_SURF2),',
              '    gsDPSetCombineLERP(TEXEL0, 0, SHADE, 0, 0, 0, 0, TEXEL0, PRIMITIVE, 0, COMBINED, 0, 0, 0, 0, COMBINED),',
              '    gsDPSetPrimColor(0, 128, 255, 255, 255, 255),',
              f'    gsDPSetTextureImage_Dolphin(G_IM_FMT_I, G_IM_SIZ_4b, 32, 32, pc_wc3_{k}_tex),',
              '    gsDPSetTile_Dolphin(G_DOLPHIN_TLUT_DEFAULT_MODE, 0, 15, GX_REPEAT, GX_REPEAT, 0, 0),',
              '    gsDPSetTileSize(G_TX_RENDERTILE, 0, 0, 124, 124),']
        base = 0
        for order, grp in dl:
            gl.append(f'    gsSPVertex(&pc_wc3_{k}_v[{base}], {len(order)}, 0),')
            idx = [order[v] for t in grp for v in t]
            cnt = len(grp)
            if len(idx) < 9: idx += [0] * (9 - len(idx))
            gl.append(f'    gsSPNTrianglesInit_5b({cnt}, ' + ', '.join(map(str, idx[:9])) + '),')
            rest = idx[9:]
            while rest:
                c = rest[:12] + [0] * (12 - len(rest[:12]))
                gl.append('    gsSPNTriangles_5b(' + ', '.join(map(str, c)) + '),')
                rest = rest[12:]
            base += len(order)
        gl += ['    gsSPEndDisplayList(),', '};']
        L += gl
        for s, (key, fr) in enumerate(d['seqs'].items()):
            vals = []
            for f in fr:
                for v in flat:
                    x, y, z = f[v]
                    vals += [int(round(x)), int(round(y)), int(round(z))]
            L.append(f'const s16 pc_wc3_{k}_f{s}[{len(vals)}] = {{' + ','.join(map(str, vals)) + '};')
        print(label, 'verts', nv, 'slots', len(flat), 'tris', len(d['T']), 'height', round(d['height'], 1), 'scale', round(scales[-1], 1), 'hash', h)
    L.append(f'Vtx* pc_wc3_vtx[{n}] = {{ ' + ', '.join(f'pc_wc3_{k}_v' for k in range(n)) + ' };')
    L.append(f'Gfx* pc_wc3_dls[{n}] = {{ ' + ', '.join(f'pc_wc3_{k}_dl' for k in range(n)) + ' };')
    L.append(f'const u16* pc_wc3_map[{n}] = {{ ' + ', '.join(f'pc_wc3_{k}_map' for k in range(n)) + ' };')
    L.append(f'int pc_wc3_nverts[{n}] = {{ ' + ', '.join(f'sizeof(pc_wc3_{k}_map) / sizeof(pc_wc3_{k}_map[0])' for k in range(n)) + ' };')
    L.append(f'const s16* pc_wc3_frames[{n}][3] = {{ ' + ', '.join('{ ' + ', '.join(f'pc_wc3_{k}_f{s}' for s in range(3)) + ' }' for k in range(n)) + ' };')
    L.append('int pc_wc3_nframes[3] = { %d, %d, %d };' % (FRAMES['stand'], FRAMES['walk'], FRAMES['act']))
    L.append(f'float pc_wc3_scale[{n}] = {{ ' + ', '.join(f'{s:.2f}f' for s in scales) + ' };')
    open(out_c, 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    main(*sys.argv[1:4])
