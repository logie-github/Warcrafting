#!/usr/bin/env python3
"""Build the Warcraft III library for the app's Town Builder.

usage: make_lib_assets.py <export.pkl> <out dir for models.bin + dds> <out json for the html builder>

models.bin (little endian): 'WCM1', u32 count, then per model:
  char name[48], f32 w, d, h (native units), u16 nmesh, then per mesh: u16 tex, u16 ngroups,
  per group: u8 nverts, u8 ntris, nverts * {s16 x, y, z, s16 u, v (u*1024), u8 shade}, 3*ntris u8 local indices.
Skins ship as tex1_32x32_<hash>_0.dds replacing a placeholder I4 texture generated by pc_lib_placeholder(tex).
"""
import sys, os, io, json, struct, pickle, base64, hashlib
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np, xxhash
from PIL import Image
from make_peon_mesh import chunks

LIGHT = np.array([.4, .8, .5]); LIGHT /= np.linalg.norm(LIGHT)

def placeholder(k):
    s = (k * 2654435761 + 1) & 0xFFFFFFFF
    out = bytearray()
    for _ in range(0x200):
        s = (s * 1103515245 + 12345) & 0xFFFFFFFF
        out.append((s >> 16) & 0xFF)
    return bytes(out)

def main(pkl, out_dir, html_json):
    res = pickle.load(open(pkl, 'rb'))
    os.makedirs(out_dir, exist_ok=True)
    texid = {}; texlist = []
    def tid(png):
        h = hashlib.md5(png).hexdigest()
        if h not in texid:
            texid[h] = len(texlist); texlist.append(png)
        return texid[h]
    names = set(); models = []; bin_parts = []
    for r in sorted(res, key=lambda r: (r['ent']['cat'], r['ent']['name'].lower())):
        ent = r['ent']; nm = ent['name']
        if nm.lower() in names: continue
        names.add(nm.lower())
        lo = np.array(r['min']); hi = np.array(r['max']); c0 = np.array([(lo[0] + hi[0]) / 2, lo[1], (lo[2] + hi[2]) / 2])
        body = bytearray(); nmesh = 0
        for me in r['meshes']:
            q = np.frombuffer(me['pos'], np.uint16).reshape(-1, 3).astype(np.float64)
            P = lo + q / 65535 * (hi - lo)
            UV = np.frombuffer(me['uv'], np.int16).reshape(-1, 2) / 2048.0
            T = np.frombuffer(me['idx'], np.uint16).reshape(-1, 3).astype(np.int64)
            N = np.zeros_like(P)
            fn = np.cross(P[T[:, 1]] - P[T[:, 0]], P[T[:, 2]] - P[T[:, 0]])
            for j in range(3): np.add.at(N, T[:, j], fn)
            N /= np.maximum(np.linalg.norm(N, axis=1, keepdims=True), 1e-9)
            shade = np.round(np.clip(np.maximum(N @ LIGHT, 0) * .55 + .55, 0, 1) * 255).astype(int)
            Q = np.round(P - c0).astype(int); U = np.clip(np.round(UV * 1024), -32768, 32767).astype(int)
            groups = chunks([tuple(int(v) for v in t) for t in T])
            body += struct.pack('<HH', tid(r['texs'][me['tex']]), len(groups)); nmesh += 1
            for grp in groups:
                order = {}
                for t in grp:
                    for v in t: order.setdefault(v, len(order))
                body += struct.pack('<BB', len(order), len(grp))
                for v in order:
                    body += struct.pack('<hhhhhB', int(Q[v][0]), int(Q[v][1]), int(Q[v][2]), int(U[v][0]), int(U[v][1]), int(shade[v]))
                for t in grp:
                    for v in t: body += struct.pack('<B', order[v])
        w, d, h = (hi - lo)[0], (hi - lo)[2], (hi - lo)[1]
        bin_parts.append(nm.encode()[:47].ljust(48, b'\0') + struct.pack('<fffH', float(w), float(d), float(h), nmesh) + bytes(body))
        models.append(dict(name=nm, cat=ent['cat'], path=ent['path'], w=float(w), d=float(d), h=float(h), r=r))
    with open(os.path.join(out_dir, 'models.bin'), 'wb') as f:
        f.write(b'WCM1' + struct.pack('<I', len(bin_parts)) + b''.join(bin_parts))
    for k, png in enumerate(texlist):
        ph = placeholder(k); h = xxhash.xxh64(ph, seed=0).hexdigest()
        Image.open(io.BytesIO(png)).convert('RGBA').save(os.path.join(out_dir, f'tex1_32x32_{h}_0.dds'), pixel_format='DXT5')
    # html data: quantised models + textures + thumbs
    H = {'models': {}, 'folders': {}, 'thumbs': {}, 'textures': []}
    tex_html = {}
    for m in models:
        r = m['r']; meshes = []
        for me in r['meshes']:
            png = r['texs'][me['tex']]; h = hashlib.md5(png).hexdigest()
            if h not in tex_html:
                im = Image.open(io.BytesIO(png)).convert('RGBA')
                if max(im.size) > 128: im.thumbnail((128, 128), Image.LANCZOS)
                b = io.BytesIO()
                if np.asarray(im)[..., 3].min() < 250: im.save(b, 'PNG', optimize=True); mime = 'image/png'
                else: im.convert('RGB').save(b, 'JPEG', quality=70); mime = 'image/jpeg'
                tex_html[h] = len(H['textures']); H['textures'].append('data:%s;base64,%s' % (mime, base64.b64encode(b.getvalue()).decode()))
            meshes.append(dict(pos=base64.b64encode(me['pos']).decode(), uv=base64.b64encode(me['uv']).decode(), idx=base64.b64encode(me['idx']).decode(), tex=tex_html[h]))
        H['models'][m['name']] = dict(path=m['path'], meshes=meshes, min=r['min'], max=r['max'])
        H['folders'].setdefault(m['cat'], []).append(m['name'])
        H['thumbs'][m['name']] = 'data:image/jpeg;base64,' + base64.b64encode(r['thumb']).decode()
    json.dump(H, open(html_json, 'w'), separators=(',', ':'))
    print(len(models), 'models,', len(texlist), 'skins, models.bin', os.path.getsize(os.path.join(out_dir, 'models.bin')) / 1e6, 'MB; html json', os.path.getsize(html_json) / 1e6, 'MB')

if __name__ == '__main__':
    main(*sys.argv[1:4])
